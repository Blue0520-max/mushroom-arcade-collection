  function row(x, y, count, spacing = 1.3) {
    return Array.from({ length: count }, (_, i) => [round(x + i * spacing), y]);
  }

  function arc(left, right, bottom, rise, count = 5) {
    return Array.from({ length: count }, (_, i) => {
      const t = i / (count - 1);
      return [round(left + (right - left) * t), round(bottom - 4 * rise * t * (1 - t))];
    });
  }

  // Each hill is [foot, summit start, summit end, foot, summit y].
  // The same edge coordinates form the floor and ramp geometry, including the shared seam.
  function terrain(width, gaps = [], hills = []) {
    const edges = [...new Set([0, width, ...gaps.flat(), ...hills.flatMap(h => h.slice(0, 4))])].sort((a, b) => a - b);
    const ground = [], slopes = [];
    function elevation(x) {
      for (const [left, ascent, descent, right, peak] of hills) {
        if (x < left || x > right) continue;
        if (x < ascent) return 13 + (peak - 13) * (x - left) / (ascent - left);
        if (x <= descent) return peak;
        return peak + (13 - peak) * (x - descent) / (right - descent);
      }
      return 13;
    }
    for (let i = 0; i < edges.length - 1; i++) {
      const left = edges[i], right = edges[i + 1];
      const mid = (left + right) / 2;
      if (gaps.some(([a, b]) => a < mid && mid < b)) continue;
      const y1 = round(elevation(left)), y2 = round(elevation(right));
      if (y1 === y2) ground.push([left, right, y1]);
      else slopes.push([left, right, y1, y2]);
    }
    return { ground, slopes };
  }

